export type IconName = keyof typeof SVG;

/** Sized, coloured with the current text colour. */
const prepared = new Map<string, string>();
function markup(name: IconName, size: number): string {
  const key = `${name}:${size}`;
  let m = prepared.get(key);
  if (!m) {
    m = SVG[name]
      .replace(/width="\d+"/, `width="${size}"`)
      .replace(/height="\d+"/, `height="${size}"`)
      .replace("<svg ", '<svg fill="currentColor" aria-hidden="true" focusable="false" ');
    prepared.set(key, m);
  }
  return m;
}

export function Icon({ name, size = 20 }: { name: IconName; size?: number }) {
  return (
    <span
      className="icon"
      style={{ width: size, height: size }}
      // Trusted, bundled SVG markup.
      dangerouslySetInnerHTML={{ __html: markup(name, size) }}
    />
  );
}
